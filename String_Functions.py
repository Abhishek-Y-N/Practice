s="Sample String"

print("Letter s count:",s.count("S"))  #Count Of Letter S

print("Split:",s.split())   #Split string

print("Lower:",s.lower())   #convert string to lower case

print("Upper:",s.upper())	#convert string to upper case

print("Startwith A:",s.startswith("a"))		#check wheather string start with letter 'a'

print("End With S:",s.endswith("s"))	#check whether string end with letter 's'

print("Partition:",s.partition("Sam"))	#Divide string in three partitions 